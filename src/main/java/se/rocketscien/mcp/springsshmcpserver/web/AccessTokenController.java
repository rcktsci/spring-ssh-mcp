package se.rocketscien.mcp.springsshmcpserver.web;

import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.server.ResponseStatusException;

import se.rocketscien.mcp.springsshmcpserver.domain.AuthTokenEntity;
import se.rocketscien.mcp.springsshmcpserver.domain.AuthTokenRepository;
import se.rocketscien.mcp.springsshmcpserver.service.AccessTokenService;

@RestController
@RequestMapping("/api/tokens")
@RequiredArgsConstructor
public class AccessTokenController {

    /**
     * REST access is authorized by {@code UiKeyFilter} alone, so unlike the MCP tools this controller applies no
     * token roles and no self-protection: an admin token may be created and the last admin token may be deleted.
     */
    private final AccessTokenService accessTokenService;
    private final AuthTokenRepository authTokenRepository;

    @GetMapping
    public List<TokenView> list() {
        return accessTokenService.list().stream().map(AccessTokenController::toView).toList();
    }

    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    public TokenSummary create(@RequestBody TokenRequest request) {
        var created = accessTokenService.create(request.canEdit(), request.canExecute(), request.executeOnly(),
                                                request.comment(), request.isTokenAdmin());
        return new TokenSummary(created.getToken().toString());
    }

    /**
     * Answers the token alone, parallel to {@code POST}: the whole {@link TokenView} is what {@code GET} is for,
     * and the REST contract asks for {@code 200 {token}} here.
     */
    @PatchMapping("/{token}")
    public TokenSummary update(@PathVariable String token, @RequestBody TokenRequest request) {
        var existing = requireToken(token);

        var updated = accessTokenService.update(existing, request.canEdit(), request.canExecute(),
                                                request.executeOnly(), request.comment(), request.isTokenAdmin());
        return new TokenSummary(updated.getToken().toString());
    }

    @DeleteMapping("/{token}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    public void delete(@PathVariable String token) {
        accessTokenService.delete(requireToken(token));
    }

    private UUID requireToken(String raw) {
        var token = parseToken(raw);
        if (authTokenRepository.findByToken(token).isEmpty()) {
            throw notFound(raw);
        }
        return token;
    }

    /**
     * {@code @PathVariable UUID} would answer {@code 400} on an unparsable value; the REST contract asks for
     * {@code 404} both for a malformed and for an unknown token, so the path segment is parsed by hand.
     */
    private UUID parseToken(String raw) {
        try {
            return UUID.fromString(raw);
        } catch (IllegalArgumentException ex) {
            throw notFound(raw);
        }
    }

    private static ResponseStatusException notFound(String raw) {
        return new ResponseStatusException(HttpStatus.NOT_FOUND, "Token not found: " + raw);
    }

    private static TokenView toView(AuthTokenEntity entity) {
        return new TokenView(
                entity.getToken().toString(),
                Boolean.TRUE.equals(entity.getCanEdit()),
                Boolean.TRUE.equals(entity.getCanExecute()),
                entity.getExecuteOnly(),
                entity.getComment(),
                Boolean.TRUE.equals(entity.getIsTokenAdmin()),
                entity.getCreatedAt(),
                entity.getUpdatedAt());
    }

    /** {@code token} in the body is ignored: the primary key is generated by the server. */
    @JsonIgnoreProperties(ignoreUnknown = true)
    public record TokenRequest(Boolean canEdit, Boolean canExecute, String[] executeOnly, String comment,
                               Boolean isTokenAdmin) {
    }

    public record TokenView(String token, boolean canEdit, boolean canExecute, String[] executeOnly, String comment,
                            boolean isTokenAdmin, LocalDateTime createdAt, LocalDateTime updatedAt) {
    }

    /** Both writes answer with the token alone: the roles, the comment and the timestamps are read back from
     * {@code GET /api/tokens}, which is also the only answer carrying the token's current state. */
    public record TokenSummary(String token) {
    }
}
